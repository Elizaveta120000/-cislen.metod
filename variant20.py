import math
import matplotlib.pyplot as plt
from scipy.optimize import brentq


# ----- сама функция и её производные (нужны для методов) -----
def f(x):
    # левая часть минус правая
    return math.log(x + 6.1) - 2 * math.sin(x - 1.4)

def df(x):
    # первая производная: (ln(x+6.1))' = 1/(x+6.1),  (2 sin(x-1.4))' = 2 cos(x-1.4)
    return 1 / (x + 6.1) - 2 * math.cos(x - 1.4)

def d2f(x):
    # вторая производная (нужна, чтобы выбрать концы в методе хорд/касательных)
    return -1 / (x + 6.1) ** 2 + 2 * math.sin(x - 1.4)


# Отрезок, на котором отделён корень (см. задание 1)
A = -2.5
B = -2.0


# ==================================================================
# ЗАДАНИЕ 1. Отделение корней.
# Строим график и печатаем таблицу знаков, чтобы найти отрезок,
# где функция меняет знак (значит, внутри есть корень).
# ==================================================================
def zadanie1():
    print("=" * 55)
    print("ЗАДАНИЕ 1. Отделение корней")
    print("=" * 55)

    # таблица знаков с шагом 0.5
    print(" x      f(x)        знак")
    x = -6.0
    prev = None
    while x <= 10.0001:
        y = f(x)
        znak = "+" if y > 0 else "-"
        smena = ""
        if prev is not None and prev[1] * y < 0:
            smena = "  <-- здесь меняется знак, есть корень"
        print("%6.2f  %+10.5f   %s%s" % (x, y, znak, smena))
        prev = (x, y)
        x += 0.5

    print("\nБерём для дальнейшей работы корень на отрезке [%.1f; %.1f]" % (A, B))
    print("Проверка: f(%.1f)=%+.5f, f(%.1f)=%+.5f -> разные знаки\n"
          % (A, f(A), B, f(B)))

    # рисуем график двух функций y1=ln(x+6.1) и y2=2 sin(x-1.4)
    xs = [(-6.0 + i * 0.02) for i in range(int((10 - (-6)) / 0.02))]
    y1 = [math.log(xx + 6.1) for xx in xs]
    y2 = [2 * math.sin(xx - 1.4) for xx in xs]
    yf = [f(xx) for xx in xs]

    plt.figure(figsize=(9, 5))
    plt.plot(xs, y1, label="y = ln(x+6.1)")
    plt.plot(xs, y2, label="y = 2 sin(x-1.4)")
    plt.plot(xs, yf, "--", label="f(x)=ln(x+6.1)-2 sin(x-1.4)")
    plt.axhline(0, color="black", linewidth=0.8)
    plt.grid(True)
    plt.legend()
    plt.title("Вариант 20: отделение корней")
    plt.savefig("variant20_graph.png", dpi=110)
    print("График сохранён в файл variant20_graph.png\n")


