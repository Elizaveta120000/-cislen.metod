# ЗАДАНИЕ 2. Метод половинного деления (бисекция), точность 1e-3.
# Делим отрезок пополам, оставляем ту половину, где функция
# меняет знак. Так длина отрезка каждый раз уменьшается вдвое.
# ==================================================================
def zadanie2(eps=1e-3):
    print("=" * 55)
    print("ЗАДАНИЕ 2. Метод половинного деления (eps=%g)" % eps)
    print("=" * 55)
    a, b = A, B
    n = 0
    print(" n     a         b         c        f(c)      (b-a)/2")
    while (b - a) / 2 > eps:
        c = (a + b) / 2
        print("%2d  %8.5f  %8.5f  %8.5f  %+9.5f  %.6f"
              % (n, a, b, c, f(c), (b - a) / 2))
        if f(a) * f(c) < 0:   # знак меняется на левой половине
            b = c
        else:                 # значит на правой
            a = c
        n += 1
    koren = (a + b) / 2
    print("Корень x = %.4f (за %d делений)\n" % (koren, n))
    return koren


# ==================================================================
# ЗАДАНИЕ 3. Метод простой итерации, точность 1e-6.
# Уравнение приводим к виду x = phi(x), где phi(x) = x - f(x)/M.
# M подбираем так, чтобы |phi'(x)| < 1 (тогда итерации сходятся).
# Здесь f'(x) > 0 на отрезке, поэтому берём M = max f'(x).
# ==================================================================
def zadanie3(eps=1e-6):
    print("=" * 55)
    print("ЗАДАНИЕ 3. Метод простой итерации (eps=%g)" % eps)
    print("=" * 55)

    # оценим M = max|f'| на отрезке (грубо, по нескольким точкам)
    M = max(abs(df(A)), abs(df(B)), abs(df((A + B) / 2)))
    M = M * 1.05   # небольшой запас, чтобы точно было |phi'|<1
    print("Берём M = %.4f, тогда phi(x) = x - f(x)/M" % M)

    def phi(x):
        return x - f(x) / M

    x = (A + B) / 2     # начальное приближение - середина
    n = 0
    print(" n      x_n            phi(x_n)        |x_n+1 - x_n|")
    while True:
        xn = phi(x)
        print("%2d   %.9f   %.9f   %.2e" % (n, x, xn, abs(xn - x)))
        if abs(xn - x) < eps:
            break
        x = xn
        n += 1
    print("Корень x = %.6f (за %d итераций)\n" % (xn, n))
    return xn


# ==================================================================
# ЗАДАНИЕ 4. Комбинированный метод хорд и касательных, точность 1e-6.
# Хорда подходит к корню с одной стороны, касательная - с другой,
# поэтому корень всё время "зажат" между ними. Останавливаемся,
# когда расстояние между приближениями меньше eps, ответ - середина.
# ==================================================================
def zadanie4(eps=1e-6):
    print("=" * 55)
    print("ЗАДАНИЕ 4. Комбинированный метод хорд и касательных (eps=%g)" % eps)
    print("=" * 55)
    a, b = A, B
    # На отрезке f''(x) > 0 (выпуклость вниз), это видно по знаку:
    print("f''(%.1f)=%+.4f, f''(%.1f)=%+.4f  -> вторая производная знак не меняет"
          % (a, d2f(a), b, d2f(b)))
    # тот конец, где f и f'' одного знака -> касательная,
    # другой конец -> хорда.
    n = 0
    print(" n   хорда(a)       касательная(b)   длина [a;b]")
    while abs(b - a) > eps:
        # хорда движет тот конец, где f*f'' < 0:
        # касательная движет тот конец, где f*f'' > 0.
        if f(a) * d2f(a) > 0:
            # касательная из a, хорда из b
            a = a - f(a) / df(a)
            b = b - f(b) * (a - b) / (f(a) - f(b))
        else:
            # касательная из b, хорда из a
            b = b - f(b) / df(b)
            a = a - f(a) * (b - a) / (f(b) - f(a))
        print("%2d   %.9f   %.9f   %.2e" % (n, a, b, abs(b - a)))
        n += 1
    koren = (a + b) / 2
    print("Корень x = %.6f (за %d шагов)\n" % (koren, n))
    return koren


# ==================================================================
# ЗАДАНИЕ 5. Готовый инструментальный пакет (SciPy), точность 1e-6.
# Функция brentq - надёжный метод Брента (комбинация бисекции,
# секущих и обратной квадратичной интерполяции).
# ==================================================================
def zadanie5(eps=1e-6):
    print("=" * 55)
    print("ЗАДАНИЕ 5. Решение через пакет SciPy (brentq)")
    print("=" * 55)
    koren = brentq(f, A, B, xtol=eps)
    print("Корень x = %.8f" % koren)
    print("Проверка: f(x) = %.2e\n" % f(koren))
    return koren


